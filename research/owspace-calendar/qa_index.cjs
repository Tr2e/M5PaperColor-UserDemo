const { chromium } = require('playwright');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(String(error)));
  await page.goto('file://'+path.join(__dirname,'output','单向历2015至2025年历史内容索引.html'));
  const count=await page.locator('.record').count();
  assert.equal(count,4018);
  await page.locator('#search').fill('2015-02-18');
  assert.equal(await page.locator('.record:visible').count(),1);
  assert.ok((await page.locator('.record:visible').innerText()).includes('宜求嗣'));
  await page.locator('#search').fill('2025-02-13');
  assert.ok((await page.locator('.record:visible').innerText()).includes('图内日期 2025-03-13'));
  await page.locator('#search').fill('2023-02-08');
  assert.ok((await page.locator('.record:visible').innerText()).includes('问答页（无宜忌）'));
  await page.locator('#search').fill('__NO_MATCH_EXPECTED__');
  assert.equal(await page.locator('.record:visible').count(),0);
  await page.locator('#clear').click();
  assert.equal(await page.locator('.record:visible').count(),count);
  assert.equal(errors.length,0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const out=path.join(__dirname,'qa');fs.mkdirSync(out,{recursive:true});
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(out,'index-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>scrollTo(0,0));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(out,'index-mobile.png')});
  await page.locator('#search').fill('2025-04-21');
  const korean=await page.locator('.record:visible').innerText();
  assert.ok(korean.includes('韩江') && korean.includes('한강'));
  assert.ok(!korean.includes('兙召'));
  await page.goto('file://'+path.join(__dirname,'output','作者姓名核对清单.html'));
  const audit=JSON.parse(fs.readFileSync(path.join(__dirname,'author_audit','summary.json'),'utf8'));
  assert.equal(await page.locator('.change').count(),audit.changed_records);
  assert.equal(await page.locator('.issue').count(),audit.source_conflicts.length+audit.source_suspected_errors.length);
  await page.locator('#q').fill('한강');
  assert.ok(await page.locator('.change:visible').count()>0);
  await page.locator('#clear').click();
  assert.equal(await page.locator('.change:visible').count(),audit.changed_records);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:path.join(out,'author-audit-desktop.png')});
  console.log(JSON.stringify({records:count,search_pass:true,page_errors:errors}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
